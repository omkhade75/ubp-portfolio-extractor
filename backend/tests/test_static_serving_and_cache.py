import re
from pathlib import Path
from fastapi.testclient import TestClient

from app.main import app
from app.config import BASE_DIR

client = TestClient(app)
DIST_DIR = BASE_DIR / "frontend" / "dist"


def test_index_html_has_no_cache_headers_and_valid_asset_references():
    """Verify / serves index.html with no-cache headers and every referenced CSS/JS asset exists and returns 200."""
    assert DIST_DIR.exists(), f"Frontend dist directory missing at {DIST_DIR}"
    index_res = client.get("/")
    assert index_res.status_code == 200
    assert "text/html" in index_res.headers.get("content-type", "")

    cache_ctrl = index_res.headers.get("cache-control", "").lower()
    assert "no-cache" in cache_ctrl
    assert "no-store" in cache_ctrl
    assert "must-revalidate" in cache_ctrl

    head_res = client.head("/")
    assert head_res.status_code == 200

    html = index_res.text
    # Extract all /assets/... script and stylesheet URLs generated by Vite
    asset_urls = re.findall(r'(?:src|href)="(/assets/[^"]+)"', html)
    assert any(u.endswith(".css") for u in asset_urls), f"No CSS asset referenced in index.html: {html}"
    assert any(u.endswith(".js") for u in asset_urls), f"No JS asset referenced in index.html: {html}"

    for asset_url in asset_urls:
        rel_path = asset_url.lstrip("/")
        disk_file = DIST_DIR / rel_path
        assert disk_file.exists(), f"Referenced asset missing on disk: {disk_file}"

        res = client.get(asset_url)
        assert res.status_code == 200, f"Asset {asset_url} returned {res.status_code}"
        asset_cc = res.headers.get("cache-control", "").lower()
        assert "immutable" in asset_cc
        if asset_url.endswith(".css"):
            assert "text/css" in res.headers.get("content-type", "")
            assert ".hidden" in res.text or ".sr-only" in res.text
        elif asset_url.endswith(".js"):
            assert "javascript" in res.headers.get("content-type", "")
            # Ensure truthful labels are compiled into bundle
            assert "Isolated Server-Side Processing" in res.text
            assert "Python Financial Extraction Engine" in res.text
            assert "Deterministic Processing / No External AI Calls" in res.text


def test_missing_hashed_asset_returns_strict_404_not_html():
    """Verify missing hashed CSS/JS assets return HTTP 404 JSON rather than SPA HTML fallback."""
    res_missing_css = client.get("/assets/index-DTUJkkxJ.css")
    assert res_missing_css.status_code == 404
    assert "text/html" not in res_missing_css.headers.get("content-type", "")

    res_missing_js = client.get("/assets/index-1R4iswpa.js")
    assert res_missing_js.status_code == 404
    assert "text/html" not in res_missing_js.headers.get("content-type", "")

    res_missing_api = client.get("/api/nonexistent-endpoint")
    assert res_missing_api.status_code == 404
